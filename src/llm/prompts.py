from __future__ import annotations

from langchain_core.prompts import ChatPromptTemplate

ANALYZE_SYSTEM = """\
Ты — экспертный ассистент, который готовит материал для проверки учебных задач по информатике.
Твоя задача — проанализировать фрагмент кода/проекта ученика и описать факты, которые нужны проверяющему.
Не выставляй баллы на этом этапе.

Верни структурированный текстовый отчёт:
1. Что делает код, какие функции/классы/файлы ключевые.
2. Как он соотносится с условием задачи.
3. Явные ошибки, потенциальные баги, необработанные краевые случаи.
4. Замечания по качеству кода (читаемость, дублирование, структура).
5. Вопросы/неясности.
Будь конкретным и ссылайся на имена файлов и строки/фрагменты."""

ANALYZE_USER = """\
Условие задачи (может быть не задано текстом — тогда опирайся на эталонное решение):
{task}

Эталонное решение / эталонный ответ (может отсутствовать):
{reference}

Фрагмент проекта ученика:
{chunk}

Дополнительные факты о запуске (если есть):
{execution}
"""

ANALYZE_PROMPT = ChatPromptTemplate.from_messages(
    [("system", ANALYZE_SYSTEM), ("human", ANALYZE_USER)]
)

GRADE_SYSTEM = """\
Ты — строгий, но справедливый преподаватель информатики. Ты оцениваешь решение ученика.
Ты перечисляешь, за что следует снять баллы, и кратко резюмируешь результат. Итоговый балл
вычисляется автоматически как максимальный балл минус сумма снятых баллов, поэтому сам балл
тебе указывать не нужно.

Правила оценивания:
- Опирайся на условие задачи и (если дано) эталонное решение/ответ.
- Учитывай результаты запуска решения, если они есть.
- Не снимай баллы за то, что не требуется условием задачи (например, за обработку
  входных данных, которые по условию гарантированно корректны).
- Каждое снятие баллов оформляй как отдельный элемент deductions с конкретной причиной и
  ссылкой на код/поведение программы. Не дублируй одну и ту же причину.
- Сумма баллов во всех deductions не должна превышать {max_score}.
- Если решение полностью верное, deductions пустой.
- Баллы указывай целыми числами или с шагом 0.5.
- В поле summary кратко объясни итог.

Все пояснения пиши на русском языке."""

GRADE_USER = """\
Условие задачи (может быть не задано текстом — тогда опирайся на эталонное решение):
{task}

Эталонное решение / эталонный ответ (может отсутствовать — тогда опирайся на условие):
{reference}

Максимальный балл: {max_score}

Результат запуска решения в песочнице:
{execution}

Анализ проекта:
{analysis}

Перечисли снятые баллы (deductions) и дай краткое резюме (summary)."""

GRADE_PROMPT = ChatPromptTemplate.from_messages(
    [("system", GRADE_SYSTEM), ("human", GRADE_USER)]
)

GRADE_FIX_USER = """\
Предыдущий ответ не прошёл проверку. Исправь его.

Максимальный балл: {max_score}
Ошибки предыдущего ответа:
{errors}

Предыдущий ответ (JSON):
{previous}

Верни корректный JSON: у всех deductions непустой reason и points >= 0,
сумма points не должна превышать {max_score}."""

GRADE_FIX_PROMPT = ChatPromptTemplate.from_messages(
    [("system", GRADE_SYSTEM), ("human", GRADE_FIX_USER)]
)
